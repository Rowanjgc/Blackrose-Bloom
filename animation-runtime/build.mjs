// Build trusted dependencies once. Generated scenes never run in this process.
import {build} from 'esbuild';
import {fileURLToPath} from 'node:url';
import {dirname, resolve} from 'node:path';
import {readFile, readdir, writeFile} from 'node:fs/promises';

const root = dirname(fileURLToPath(import.meta.url));
const runtime = await build({
  absWorkingDir: root,
  stdin: {contents: `export * as core from '@motion-canvas/core';
    export * as two from '@motion-canvas/2d';
    export * as jsx from '@motion-canvas/2d/lib/jsx-runtime';`, resolveDir: root},
  bundle: true, format: 'iife', globalName: 'BlackroseMotion',
  target: 'es2022', minify: true, legalComments: 'eof', metafile: true,
  define: {'import.meta.env': '{}', 'import.meta.hot': 'undefined'},
  outfile: resolve(root, '../src/blackrose/gui/static/motion-canvas-runtime.js'),
});
// Preserve the licenses of the packages actually included in the browser bundle.
// Compiler dependencies retain their own notices in npm's installed packages.
const packages = new Map();
for (const input of Object.keys(runtime.metafile.inputs)) {
  if (!input.startsWith('node_modules/')) continue;
  let directory = dirname(resolve(root, input));
  while (directory !== root) {
    try {
      const metadata = JSON.parse(await readFile(resolve(directory, 'package.json'), 'utf8'));
      if (metadata.name) {
        packages.set(directory, metadata);
        break;
      }
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    directory = dirname(directory);
  }
}
const notices = ['Third-party packages in the Blackrose Motion Canvas browser bundle.\n'
  + 'Generated by animation-runtime/build.mjs from the installed locked packages.\n'];
for (const [directory, metadata] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  const files = (await readdir(directory)).filter(name => /^(licen[cs]e|copying|notice)([._-].*)?$/i.test(name)).sort();
  if (!files.length) throw new Error(`No license notice found for ${metadata.name}`);
  notices.push(`\n=== ${metadata.name} ${metadata.version} (${metadata.license || 'see notice'}) ===\n`);
  for (const file of files) notices.push(`\n--- ${file} ---\n${await readFile(resolve(directory, file), 'utf8')}`);
}
await writeFile(resolve(root, '../src/blackrose/gui/static/motion-canvas-NOTICES.txt'), notices.join('\n'));
// Let esbuild check scene imports against the actual installed API, without
// executing either the library or the model's module in Node.
const exportsByPackage = {};
for (const [name, namespace] of [['@motion-canvas/core', 'core'], ['@motion-canvas/2d', 'two'],
  ['@motion-canvas/2d/lib/jsx-runtime', 'jsx']]) {
  const result = await build({absWorkingDir: root,
    stdin: {contents: `export * from '${name}';`, resolveDir: root},
    bundle: true, write: false, format: 'esm', metafile: true, logLevel: 'silent',
    define: {'import.meta.env': '{}', 'import.meta.hot': 'undefined'}});
  exportsByPackage[name] = {namespace, names: Object.values(result.metafile.outputs)[0].exports};
}
await writeFile(resolve(root, 'exports.json'), JSON.stringify(exportsByPackage));
